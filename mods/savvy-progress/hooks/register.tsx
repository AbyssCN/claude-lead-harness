type TermUi = Pick<Elements['terminal'], 'Box' | 'Text'>

// Pixel rows drawn two per line with half blocks: the top pixel is the glyph, the bottom its background.
function halfBlocks(ui: TermUi, pixels: string[], colors: Record<string, string>, key: string) {
  const { Box, Text } = ui
  const lines = []
  for (let y = 0; y < pixels.length; y += 2) {
    const top = pixels[y] ?? ''
    const bottom = pixels[y + 1] ?? ''
    const cells = [...top].map((t, x) => {
      const a = colors[t]
      const b = colors[bottom[x] ?? '.']
      if (a && b) return <Text key={`c${x}`} color={a} backgroundColor={b}>▀</Text>
      if (a) return <Text key={`c${x}`} color={a}>▀</Text>
      if (b) return <Text key={`c${x}`} color={b}>▄</Text>
      return <Text key={`c${x}`}> </Text>
    })
    lines.push(<Text key={`${key}-${y}`}>{cells}</Text>)
  }
  return (
    <Box key={key} flexDirection="column" flexShrink={0}>
      {lines}
    </Box>
  )
}

const waveText = (ui: TermUi, at: number, isRunning: boolean) => {
  const { Text } = ui
  const frame = isRunning ? WAVE_FRAMES[Math.floor(at / 1000) % WAVE_FRAMES.length] ?? '' : WAVE_FRAMES[0] ?? ''
  return [...frame].map((ch, i) => (
    <Text key={`w${i}`} color={WAVE_COLORS[i]}>
      {ch}
    </Text>
  ))
}

// --- terminal drawing: the same rows in text.

const ctxBar = (pct: number, width: number): string => {
  const filled = Math.round((width * pct) / 100)
  return '█'.repeat(filled) + '░'.repeat(Math.max(0, width - filled))
}

